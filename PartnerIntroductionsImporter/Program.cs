    // =====================================================================
    // OVERVIEW
    // =====================================================================
    // Phase 1 (StageIncomingEmails):
    //   Reads unread emails -> parses lead fields -> INSERTs one row per lead
    //   into dbo.PartnerLeads with Status='Pending' -> marks email as read.
    //   Run CreateLeadsTable.sql once against the DB before using this.
    //
    // Phase 2 (ProcessPendingLeads):
    //   SELECTs rows where Status='Pending' -> builds the APMIMPORT XML ->
    //   submits to InStream -> UPDATEs the row with Success/Failed,
    //   EpaProspectRef/EpaPolicyRef, and the raw request/response for audit.
    //
    // Splitting these two steps means a failed InStream call never re-reads
    // the inbox, and every lead has a permanent DB record + audit trail
    // regardless of whether the import succeeded.
    // =====================================================================
    //
    // FIELD MAPPING NOTES (confirmed via live testing against Open Interchange)
    //   APMCLIENT / P.CM   : NAME, ADDR1, ADDR2, ADDR3, PCODE, TEL, EMAIL, NOTES
    //                        (REFNO omitted - confirmed optional, auto-generated by back office)
    //   APMPOL    / P.PY   : PTYPE = "HQ"  (household - confirmed)
    //   APMPOL    / HW     : Riskaddr1-3, Riskpcode, Commaddr1-3, Commpcode,
    //                        Buildings, Contents, Specitems (Yes/No),
    //                        Buildingssi, Contentssi, Specitemssi
    //   APMPOL    / H1     : Housetype, Bedrooms, Adults, Children
    //   APMPOL    / H3     : Buildtotxs, Byearsncb  (buildings excess/NCD - confirmed)
    //   APMPOL    / HJ     : Contstotxs, Cyearsncb  (contents excess/NCD - confirmed)
    //   APMPOL    / HN     : Proptitle, Propsurname, Propforenames, Propdob,
    //                        Occtype1 (must be an exact value from the valid occupation
    //                        list - "Employed"/"Self-Employed" etc. are REJECTED)
    //
    // STILL UNMAPPED (no confirmed field found - preserved in NOTES only):
    //   - Property Ownership, Previous Claims, Year of Build
    // =====================================================================

