        static async Task StageIncomingEmails()
        {
            Console.WriteLine("Connecting to mailbox: " + MAILBOX);

            var credential = new ClientSecretCredential(TENANT_ID, CLIENT_ID, CLIENT_SECRET);
            var graphClient = new GraphServiceClient(credential);

            // Pull from both Inbox and Junk Email - referral emails from external partner
            // senders sometimes get misclassified as junk and would otherwise be missed entirely.
            var emails = new List<Message>();
            emails.AddRange(await FetchAllMessages(graphClient, "Inbox"));
            emails.AddRange(await FetchAllMessages(graphClient, "JunkEmail"));

           
            Console.WriteLine($"Total emails found (Inbox + Junk, last {EMAIL_LOOKBACK_DAYS} days, all read-status): " + emails.Count);
            int staged = 0, skipped = 0, errored = 0;

            using (var conn = new SqlConnection(DB_CONNECTION_STRING))
            {
                await conn.OpenAsync();

                foreach (var email in emails)
                {
                    Console.WriteLine("----------------------------------------");
                    Console.WriteLine("Processing email: " + email.Subject);
                    string sender = email.From?.EmailAddress?.Address ?? "";
                    Console.WriteLine("  From: " + sender);

                    bool isPolicyLink = IsPolicyLinkEmail(email);

                    if (!isPolicyLink && !MailboxIsInCc(email))
                    {
                        Console.WriteLine("  Skipped - mailbox address not found in Cc (and not a PolicyLink lead)");
                        skipped++;
                        continue;
                    }

                    try
                    {
                        LeadDetails lead;
                        if (isPolicyLink)
                        {
                            Console.WriteLine("  PolicyLink lead - using PolicyLink parser");
                            lead = ParsePolicyLinkLead(email.Body.Content);
                            lead.Source = POLICYLINK_SOURCE;
                            LogPolicyLinkLead(lead);
                        }
                        else
                        {
                            lead = ParseLeadFromEmail(email.Body.Content);
                            lead.Source = DetermineSourceFromSubject(email.Subject);
                        }
                        Console.WriteLine("  Parsed: " + lead.Name + " | Source: " + (lead.Source ?? "(none)"));

                        bool inserted = await InsertLead(conn, email.Id, email.Subject, email.ReceivedDateTime, lead);

                        if (inserted)
                        {
                            Console.WriteLine("  Staged into PartnerLeads (Status=Pending)");
                            staged++;
                        }
                        else
                        {
                            Console.WriteLine("  Already staged previously - skipped duplicate");
                            skipped++;
                        }

                        // Mark as read separately - a failure here is a Graph API permissions issue,
                        // NOT a staging failure. The lead is already safely in the DB either way,
                        // and the EmailId uniqueness check prevents re-staging it next run.
                        try
                        {
                            await MarkEmailAsRead(email.Id);
                        }
                        catch (Exception markEx)
                        {
                            Console.WriteLine("  WARNING: could not mark email as read (lead is still staged OK): " + markEx.Message);
                        }
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine("  Error staging email: " + ex.Message);
                        errored++;
                    }
                }
            }

            Console.WriteLine("----------------------------------------");
            Console.WriteLine($"Staging complete. Staged: {staged}, Skipped (duplicate): {skipped}, Errors: {errored}");
        }

        // Fetches every message in the given mail folder (well-known names like
        // "Inbox" / "JunkEmail" work directly), following pagination until fully exhausted.
        // No isRead filter - dedupe is handled entirely by the EmailId uniqueness check in
        // dbo.PartnerLeads, so we don't depend on the (previously broken) mark-as-read flag
        // for correctness. Every run just re-scans everything; already-staged emails are
        // cheaply skipped by the DB check.
        static async Task<List<Message>> FetchAllMessages(GraphServiceClient graphClient, string folderName)
        {
            var results = new List<Message>();
            var cutoff = DateTimeOffset.UtcNow.AddDays(-EMAIL_LOOKBACK_DAYS);
            string cutoffFilter = $"receivedDateTime ge {cutoff:yyyy-MM-ddTHH:mm:ssZ}";

            var page = await graphClient.Users[MAILBOX].MailFolders[folderName].Messages.GetAsync(config =>
            {
                config.QueryParameters.Top = 50;
                config.QueryParameters.Orderby = new[] { "receivedDateTime desc" };
                config.QueryParameters.Filter = cutoffFilter;
                config.QueryParameters.Select = new[] { "id", "subject", "receivedDateTime", "body", "from", "ccRecipients", "toRecipients", "isRead" };
            });

            while (page != null)
            {
                if (page.Value != null) results.AddRange(page.Value);

                if (!string.IsNullOrEmpty(page.OdataNextLink))
                    page = await graphClient.Users[MAILBOX].MailFolders[folderName].Messages.WithUrl(page.OdataNextLink).GetAsync();
                else
                    page = null;
            }

            return results;
        }

        static async Task MarkEmailAsRead(string emailId)
        {
            var credential = new ClientSecretCredential(TENANT_ID, CLIENT_ID, CLIENT_SECRET);
            var graphClient = new GraphServiceClient(credential);

            await graphClient.Users[MAILBOX].Messages[emailId].PatchAsync(
                new Message { IsRead = true });
        }

        // Only referral emails where this mailbox is explicitly CC'd should be imported -
        // this filters out anything else that happens to land in the shared inbox.
        static bool MailboxIsInCc(Message email)
        {
            if (email.CcRecipients == null) return false;

            return email.CcRecipients.Any(r =>
                r.EmailAddress != null &&
                !string.IsNullOrEmpty(r.EmailAddress.Address) &&
                r.EmailAddress.Address.Equals(MAILBOX, StringComparison.OrdinalIgnoreCase));
        }

        // PolicyLink leads are sent From POLICYLINK_SENDER directly To this mailbox.
        static bool IsPolicyLinkEmail(Message email)
        {
            string from = email.From?.EmailAddress?.Address;
            if (string.IsNullOrEmpty(from) || !from.Equals(POLICYLINK_SENDER, StringComparison.OrdinalIgnoreCase))
                return false;

            return email.ToRecipients != null && email.ToRecipients.Any(r =>
                r.EmailAddress != null &&
                !string.IsNullOrEmpty(r.EmailAddress.Address) &&
                r.EmailAddress.Address.Equals(MAILBOX, StringComparison.OrdinalIgnoreCase));
        }

