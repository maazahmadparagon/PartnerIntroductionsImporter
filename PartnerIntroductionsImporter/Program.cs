        // Safety backstop: even after widening columns, truncate any value that's still
        // longer than its column limit so a single unexpectedly long field (e.g. a huge
        // "Any Specified Items" list) never causes the whole insert to fail.
        static string Truncate(string value, int maxLength)
        {
            if (string.IsNullOrEmpty(value)) return value ?? "";
            return value.Length <= maxLength ? value : value.Substring(0, maxLength);
        }

        static object NullIfEmpty(string value)
        {
            return string.IsNullOrWhiteSpace(value) ? (object)DBNull.Value : value;
        }

