        // MAINTENANCE - one-off fix for rows stuck on the default postcode
        // () because they were staged before the postcode parsing fix.
        // Re-fetches the original email by EmailId and re-runs GetPostCode against it.
        // Run with: dotnet run -- --fix-postcodes
        // =====================================================================
        static async Task FixStalePostcodes()
        {
            var credential = new ClientSecretCredential(TENANT_ID, CLIENT_ID, CLIENT_SECRET);
            var graphClient = new GraphServiceClient(credential);

            var affected = new List<(int LeadId, string EmailId, string CurrentAddress1)>();

            using (var conn = new SqlConnection(DB_CONNECTION_STRING))
            {
                await conn.OpenAsync();

                const string selectSql = @"
                    SELECT LeadId, EmailId, Address1
                    FROM dbo.PartnerLeads
                    WHERE PostCode = @TempMarker";

                using (var cmd = new SqlCommand(selectSql, conn))
                {
                    cmd.Parameters.AddWithValue("@TempMarker", "TEMP-FIX");
                    using (var reader = await cmd.ExecuteReaderAsync())
                    {
                        while (await reader.ReadAsync())
                        {
                            affected.Add((reader.GetInt32(0), reader.GetString(1), reader.IsDBNull(2) ? "" : reader.GetString(2)));
                        }
                    }
                }
            }

            Console.WriteLine($"Rows flagged TEMP-FIX: {affected.Count}");

            int fixedCount = 0, stillUnresolved = 0, fetchErrors = 0;

            using (var conn = new SqlConnection(DB_CONNECTION_STRING))
            {
                await conn.OpenAsync();

                foreach (var row in affected)
                {
                    Console.WriteLine("----------------------------------------");
                    Console.WriteLine($"LeadId {row.LeadId} ({row.CurrentAddress1}) - refetching email {row.EmailId}");

                    try
                    {
                        // Message endpoint works by id regardless of which folder (Inbox/Junk) it's in.
                        var message = await graphClient.Users[MAILBOX].Messages[row.EmailId].GetAsync(config =>
                        {
                            config.QueryParameters.Select = new[] { "body" };
                        });

                        string body = PreprocessEmailBody(message?.Body?.Content);
                        string correctedPostcode = GetPostCode(body);

                        if (!string.IsNullOrWhiteSpace(correctedPostcode) &&
                            !correctedPostcode.Equals(DEFAULT_POSTCODE, StringComparison.OrdinalIgnoreCase))
                        {
                            const string updateSql = "UPDATE dbo.PartnerLeads SET PostCode = @PostCode WHERE LeadId = @LeadId";
                            using (var cmd = new SqlCommand(updateSql, conn))
                            {
                                cmd.Parameters.AddWithValue("@PostCode", correctedPostcode);
                                cmd.Parameters.AddWithValue("@LeadId", row.LeadId);
                                await cmd.ExecuteNonQueryAsync();
                            }

                            Console.WriteLine($"  Fixed: {DEFAULT_POSTCODE} -> {correctedPostcode}");
                            fixedCount++;
                        }
                        else
                        {
                            Console.WriteLine("  Could not extract a real postcode from the email - left as-is");
                            stillUnresolved++;
                        }
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine("  Error refetching/updating: " + ex.Message);
                        fetchErrors++;
                    }
                }
            }

            Console.WriteLine("----------------------------------------");
            Console.WriteLine($"Postcode fix complete. Fixed: {fixedCount}, Unresolved: {stillUnresolved}, Errors: {fetchErrors}");
            Console.WriteLine();
            Console.WriteLine("NOTE: This only corrects dbo.PartnerLeads. Any rows already Status='Success'");
            Console.WriteLine("were already sent to Open Interchange with the OLD postcode - that back-office");
            Console.WriteLine("record is NOT touched by this. See the follow-up step for correcting those.");
        }

