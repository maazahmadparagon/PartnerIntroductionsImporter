        static async Task<(string Refno, DateTime? DateFirstCont)?> FindExistingProspect(
    SqlConnection thamesConn, string email, string tel, string postcode)
        {
            const string sql = @"
    SELECT TOP 1 Refno, Date_first_cont
    FROM dbo.ic_Daprospect
    WHERE LOWER(LTRIM(RTRIM(Email))) = LOWER(@Email)
      AND LTRIM(RTRIM(Tel)) = @Tel
      AND LOWER(LTRIM(RTRIM(pcode))) = LOWER(@Postcode)
      AND @Email <> '' AND @Tel <> '' AND @Postcode <> ''
    ORDER BY Date_first_cont ASC";

