        static string BuildApmImportXml(LeadDetails lead)
        {
            // Partners that send separate name fields (PolicyLink) use them as-is so that
            // multi-word surnames aren't split; everyone else is split from the full name.
            var (title, forenames, surname) = !string.IsNullOrWhiteSpace(lead.LastName)
                ? (lead.Title ?? "", lead.FirstName ?? "", lead.LastName)
                : SplitName(lead.Name);

            bool buildingsCover = CoverIncludes(lead.CoverType, "Building");
            bool contentsCover = CoverIncludes(lead.CoverType, "Content");
            bool specItemsPresent = !string.IsNullOrWhiteSpace(lead.SpecifiedItems);

            int buildingsSi = ExtractNumber(lead.BuildingsAmount);
            int contentsSi = ExtractNumber(lead.ContentsAmount);
            int specItemsSi = ExtractNumber(lead.SpecifiedItems);
            int excess = ExtractNumber(lead.Excess, 250);
            int bedrooms = ExtractNumber(lead.Bedrooms, 3);
            int adults = ExtractNumber(lead.Occupants, 2);
            int buildingsNcd = ExtractNumber(lead.BuildingsNCD, 0);
            int contentsNcd = ExtractNumber(lead.ContentsNCD, 0);

            var unmappedNotes = new List<string>();
            if (!string.IsNullOrWhiteSpace(lead.PropertyOwnership))
                unmappedNotes.Add("Ownership: " + lead.PropertyOwnership);
            if (!string.IsNullOrWhiteSpace(lead.PreviousClaims))
                unmappedNotes.Add("Prev claims: " + lead.PreviousClaims);
            if (!string.IsNullOrWhiteSpace(lead.YearOfBuild))
                unmappedNotes.Add("Year built: " + lead.YearOfBuild);
            if (!string.IsNullOrWhiteSpace(lead.PersonalPossessions))
                unmappedNotes.Add("Possessions: " + lead.PersonalPossessions);

            string notes = "Partner intro lead";
            if (unmappedNotes.Count > 0)
            {
                string extra = string.Join("; ", unmappedNotes);
                if ((notes + " - " + extra).Length <= 60)
                    notes = notes + " - " + extra;
            }

            var sb = new StringBuilder();
            sb.Append("<APMIMPORT>");

            // Source is set directly at creation time now (confirmed working via live test -
            // SOURCE maps to Source_CR01_VTId), rather than via a separate post-import SQL update.
            // Source is stored at staging time; rows staged before the Source column existed
            // fall back to matching the subject line.
            string source = !string.IsNullOrWhiteSpace(lead.Source)
                ? lead.Source
                : DetermineSourceFromSubject(lead.EmailSubject);

            sb.Append("<APMCLIENT><P.CM>");
            sb.Append("<NAME>").Append(XmlEscape(lead.Name)).Append("</NAME>");
            sb.Append("<ADDR1>").Append(XmlEscape(lead.Address1)).Append("</ADDR1>");
            sb.Append("<ADDR2>").Append(XmlEscape(lead.Address2)).Append("</ADDR2>");
            sb.Append("<ADDR3>").Append(XmlEscape(lead.Address3)).Append("</ADDR3>");
            sb.Append("<PCODE>").Append(XmlEscape(lead.PostCode)).Append("</PCODE>");
            sb.Append("<TEL>").Append(XmlEscape(lead.ContactNumber)).Append("</TEL>");
            sb.Append("<EMAIL>").Append(XmlEscape(lead.Email)).Append("</EMAIL>");
            if (!string.IsNullOrWhiteSpace(source))
                sb.Append("<SOURCE>").Append(XmlEscape(source)).Append("</SOURCE>");
            sb.Append("<NOTES>").Append(XmlEscape(notes)).Append("</NOTES>");
            sb.Append("</P.CM></APMCLIENT>");

            sb.Append("<APMPOL>");
            sb.Append("<P.PY><PTYPE>HQ</PTYPE></P.PY>");

            sb.Append("<HW>");
            sb.Append("<Riskaddr1>").Append(XmlEscape(lead.Address1)).Append("</Riskaddr1>");
            sb.Append("<Riskaddr2>").Append(XmlEscape(lead.Address2)).Append("</Riskaddr2>");
            sb.Append("<Riskaddr3>").Append(XmlEscape(lead.Address3)).Append("</Riskaddr3>");
            sb.Append("<Riskpcode>").Append(XmlEscape(lead.PostCode)).Append("</Riskpcode>");
            sb.Append("<Commaddr1>").Append(XmlEscape(lead.Address1)).Append("</Commaddr1>");
            sb.Append("<Commaddr2>").Append(XmlEscape(lead.Address2)).Append("</Commaddr2>");
            sb.Append("<Commaddr3>").Append(XmlEscape(lead.Address3)).Append("</Commaddr3>");
            sb.Append("<Commpcode>").Append(XmlEscape(lead.PostCode)).Append("</Commpcode>");
            sb.Append("<Buildings>").Append(buildingsCover ? "Yes" : "No").Append("</Buildings>");
            sb.Append("<Contents>").Append(contentsCover ? "Yes" : "No").Append("</Contents>");
            sb.Append("<Specitems>").Append(specItemsPresent ? "Yes" : "No").Append("</Specitems>");
            if (buildingsCover) sb.Append("<Buildingssi>").Append(buildingsSi).Append("</Buildingssi>");
            if (contentsCover) sb.Append("<Contentssi>").Append(contentsSi).Append("</Contentssi>");
            if (specItemsPresent) sb.Append("<Specitemssi>").Append(specItemsSi).Append("</Specitemssi>");
            sb.Append("</HW>");

            sb.Append("<H1>");
            sb.Append("<Housetype>").Append(XmlEscape(NormalizeHousetype(lead.PropertyType))).Append("</Housetype>");
            sb.Append("<Bedrooms>").Append(bedrooms).Append("</Bedrooms>");
            sb.Append("<Adults>").Append(adults).Append("</Adults>");
            sb.Append("<Children>0</Children>");
            sb.Append("</H1>");

            if (buildingsCover)
            {
                sb.Append("<H3>");
                sb.Append("<Buildtotxs>").Append(excess).Append("</Buildtotxs>");
                sb.Append("<Byearsncb>").Append(buildingsNcd).Append("</Byearsncb>");
                sb.Append("</H3>");
            }

            if (contentsCover)
            {
                sb.Append("<HJ>");
                sb.Append("<Contstotxs>").Append(excess).Append("</Contstotxs>");
                sb.Append("<Cyearsncb>").Append(contentsNcd).Append("</Cyearsncb>");
                sb.Append("</HJ>");
            }

            sb.Append("<HN>");
            sb.Append("<Proptitle>").Append(XmlEscape(title)).Append("</Proptitle>");
            sb.Append("<Propsurname>").Append(XmlEscape(surname)).Append("</Propsurname>");
            sb.Append("<Propforenames>").Append(XmlEscape(forenames)).Append("</Propforenames>");
            sb.Append("<Propdob>").Append(XmlEscape(lead.DateOfBirth)).Append("</Propdob>");
            sb.Append("<Occtype1>").Append(XmlEscape(SanitizeOccupation(lead.Occupation))).Append("</Occtype1>");
            sb.Append("</HN>");

            sb.Append("</APMPOL>");
            sb.Append("</APMIMPORT>");

            return sb.ToString();
        }

