        static string PreprocessEmailBody(string rawBody)
        {
            if (string.IsNullOrEmpty(rawBody)) return "";

            string body = rawBody;
            body = System.Net.WebUtility.HtmlDecode(body);
            body = Regex.Replace(body, @"<\s*br\s*/?\s*>", "\n", RegexOptions.IgnoreCase);
            body = Regex.Replace(body, @"</\s*(p|div|li|tr|h[1-6])\s*>", "\n", RegexOptions.IgnoreCase);
            body = Regex.Replace(body, "<[^>]+>", "");
            body = Regex.Replace(body, @"[ \t]+", " ");
            body = Regex.Replace(body, @"\n{2,}", "\n");

            return body.Trim();
        }

        // ---- PolicyLink format: "Label:    value", one field per line, grouped under
        // section headings ("contact details", "proposer", ...) that are ignored. ----
        static LeadDetails ParsePolicyLinkLead(string emailBody)
        {
            emailBody = PreprocessEmailBody(emailBody);
            var lead = new LeadDetails();

            lead.Product = GetColonFieldValue(emailBody, "Product") ?? GetFieldValue(emailBody, "Product") ?? "";

            lead.Title = NormalizeTitle(GetColonFieldValue(emailBody, "Title"));
            lead.FirstName = GetColonFieldValue(emailBody, "First Name") ?? "";
            lead.LastName = GetColonFieldValue(emailBody, "Last Name") ?? "";
            string fullName = string.Join(" ", new[] { lead.Title, lead.FirstName, lead.LastName }
                .Where(s => !string.IsNullOrWhiteSpace(s)));
            lead.Name = string.IsNullOrWhiteSpace(fullName) ? "Unknown" : fullName;

            lead.DateOfBirth = GetColonFieldValue(emailBody, "Date Of Birth") ?? DEFAULT_DOB;
            lead.Email = GetColonFieldValue(emailBody, "Email") ?? "";
            lead.ContactNumber = GetColonFieldValue(emailBody, "Telephone") ?? "";

            // Open GI only has 3 address lines - Address3/Address4/City are combined into line 3.
            lead.Address1 = GetColonFieldValue(emailBody, "Address1") ?? DEFAULT_ADDRESS1;
            lead.Address2 = GetColonFieldValue(emailBody, "Address2") ?? "";
            lead.Address3 = string.Join(", ", new[]
            {
                GetColonFieldValue(emailBody, "Address3"),
                GetColonFieldValue(emailBody, "Address4"),
                GetColonFieldValue(emailBody, "City")
            }.Where(s => !string.IsNullOrWhiteSpace(s)));

            // The insured property's postcode is used everywhere; the proposer's home
            // postcode is only a fallback if Property Postcode is missing.
            string propertyPostcode = GetColonFieldValue(emailBody, "Property Postcode");
            lead.PostCode = propertyPostcode ?? GetColonFieldValue(emailBody, "Postcode") ?? DEFAULT_POSTCODE;
            if (propertyPostcode == null)
                Console.WriteLine("  WARNING: Property Postcode missing - using proposer Postcode");

            lead.CoverDate = GetColonFieldValue(emailBody, "Cover Date") ?? "";
            lead.CoverType = MapPolicyLinkCoverLevel(GetColonFieldValue(emailBody, "Cover Level"));
            lead.PropertyUse = GetColonFieldValue(emailBody, "Property Use") ?? "";

            // Every "Property Type X: Yes" flag is kept for reference; Housetype sent to
            // Open GI is still the fixed default (see NormalizeHousetype).
            var propertyTypes = Regex.Matches(emailBody, @"^[ \t]*Property Type (.+?)[ \t]*:[ \t]*Yes[ \t\r]*$",
                    RegexOptions.IgnoreCase | RegexOptions.Multiline)
                .Cast<Match>().Select(m => m.Groups[1].Value.Trim()).ToList();
            lead.PropertyType = propertyTypes.Count > 0 ? string.Join(", ", propertyTypes) : DEFAULT_PROPERTY_TYPE;

            // Property Value is used as the buildings sum insured.
            lead.BuildingsAmount = GetColonFieldValue(emailBody, "Property Value") ?? "0";
            lead.ContentsAmount = "0";

            // Not supplied by PolicyLink - same defaults as the other partners.
            lead.Bedrooms = DEFAULT_BEDROOMS;
            lead.Occupants = DEFAULT_OCCUPANTS;
            lead.Occupation = DEFAULT_OCCUPATION;
            lead.Excess = DEFAULT_EXCESS;
            lead.ContentsNCD = "0";
            lead.BuildingsNCD = "0";
            lead.YearOfBuild = "";
            lead.SpecifiedItems = "";
            lead.PersonalPossessions = "0";
            lead.PreviousClaims = "0";
            lead.PropertyOwnership = "Owner";

            if (string.IsNullOrWhiteSpace(lead.DateOfBirth)) lead.DateOfBirth = DEFAULT_DOB;
            if (string.IsNullOrWhiteSpace(lead.Address1)) lead.Address1 = DEFAULT_ADDRESS1;

            return lead;
        }

        // Matches "Label:" at the start of a line so that e.g. "Postcode" never picks up
        // "Property Postcode". Returns null when the label is absent or its value is blank.
        static string GetColonFieldValue(string emailBody, string label)
        {
            var match = Regex.Match(emailBody, @"^[ \t]*" + Regex.Escape(label) + @"[ \t]*:[ \t]*(.*)$",
                RegexOptions.IgnoreCase | RegexOptions.Multiline);
            if (!match.Success) return null;

            string value = match.Groups[1].Value.Trim();
            return string.IsNullOrWhiteSpace(value) ? null : value;
        }

        static string MapPolicyLinkCoverLevel(string coverLevel)
        {
            if (string.IsNullOrWhiteSpace(coverLevel)) return "Buildings & Contents";
            string c = coverLevel.Trim().ToLowerInvariant();
            if (c.Contains("building") && !c.Contains("content")) return "Buildings";
            if (c.Contains("content") && !c.Contains("building")) return "Contents";
            return "Buildings & Contents";
        }

        static string NormalizeTitle(string title)
        {
            if (string.IsNullOrWhiteSpace(title)) return "";
            string t = title.Replace(".", "").Trim();
