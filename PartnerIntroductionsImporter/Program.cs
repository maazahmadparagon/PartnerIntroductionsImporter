    // Writes everything to both the console and the run's log file.
    class TeeWriter : TextWriter
    {
        private readonly TextWriter _console;
        private readonly TextWriter _file;

        public TeeWriter(TextWriter console, TextWriter file)
        {
            _console = console;
            _file = file;
        }

        public override Encoding Encoding => _console.Encoding;

        public override void Write(char value)
        {
            _console.Write(value);
            try { _file.Write(value); } catch { /* never let logging break a run */ }
        }

        public override void Write(string value)
        {
            _console.Write(value);
            try { _file.Write(value); } catch { }
        }

        public override void WriteLine(string value)
        {
            _console.WriteLine(value);
            try { _file.WriteLine(value); } catch { }
        }

        public override void Flush()
        {
            _console.Flush();
            try { _file.Flush(); } catch { }
        }
    }

