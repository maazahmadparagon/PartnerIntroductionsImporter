        static async Task<string> SubmitToInStream(string xmlPayload)
        {
            using (var client = new HttpClient())
            {
                string soapRequest = $@"<?xml version=""1.0"" encoding=""utf-8""?>
<soapenv:Envelope xmlns:soapenv=""http://schemas.xmlsoap.org/soap/envelope/"" xmlns:ns1=""www.opengi.co.uk"">
  <soapenv:Header/>
  <soapenv:Body>
    <ns1:inStreamMessage>
      <branch>{BRANCH}</branch>
      <marsReference>{MARS_REFERENCE}</marsReference>
      <bNumber>{B_NUMBER}</bNumber>
      <licenceKey>{LICENCE_KEY}</licenceKey>
      <xmlSubmission>{System.Security.SecurityElement.Escape(xmlPayload)}</xmlSubmission>
      <timeout>{TIMEOUT}</timeout>
    </ns1:inStreamMessage>
  </soapenv:Body>
</soapenv:Envelope>";

                var content = new StringContent(soapRequest, Encoding.UTF8, "text/xml");
                content.Headers.Add("SOAPAction", "\"\"");

                var response = await client.PostAsync(INSTREAM_URL, content);
                return await response.Content.ReadAsStringAsync();
            }
        }

        static string XmlEscape(string value)
        {
            if (string.IsNullOrEmpty(value)) return "";
            return System.Security.SecurityElement.Escape(value);
        }
    }

