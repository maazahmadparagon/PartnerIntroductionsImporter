        static string Setting(string key)
        {
            string value = System.Configuration.ConfigurationManager.AppSettings[key];
            if (string.IsNullOrWhiteSpace(value))
                throw new InvalidOperationException($"Missing setting '{key}' - check secrets.config next to the exe.");
            return value;
        }

        // Returns the names of any required settings that are missing or blank.
        static List<string> MissingSettings()
        {
            return RequiredSettings
                .Where(k => string.IsNullOrWhiteSpace(System.Configuration.ConfigurationManager.AppSettings[k]))
                .ToList();
        }

