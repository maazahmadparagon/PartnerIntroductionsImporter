        // PHASE 3 - SET PROSPECT SOURCE (ic_Daprospect) BASED ON EMAIL SUBJECT
        // =====================================================================
        // Only processes rows with Status = 'Success' (i.e. already successfully
        // imported into Open Interchange, so a real EpaProspectRef exists).
        // Once the Source is set, the row's Status is advanced to
        // 'Success-SourceSet' so it's never picked up again on future runs -
        // this makes the step naturally idempotent without a separate tracking column.
        //
        // ASSUMPTION: Thamesbank.dbo.ic_Daprospect is on the SAME SQL Server instance
        // as PartnerLeads. If it's on a different server, this cross-database query
        // needs to be replaced with a linked server reference instead.
        static async Task UpdateProspectSources()
        {
            var candidates = new List<(int LeadId, string EmailSubject, string EpaProspectRef)>();

            using (var leadsConn = new SqlConnection(DB_CONNECTION_STRING))
            {
                await leadsConn.OpenAsync();

                const string selectSql = @"
                    SELECT LeadId, EmailSubject, EpaProspectRef
                    FROM dbo.PartnerLeads
                    WHERE Status = 'Success'
                      AND EpaProspectRef IS NOT NULL
                      AND EpaProspectRef <> ''";

                using (var cmd = new SqlCommand(selectSql, leadsConn))
                using (var reader = await cmd.ExecuteReaderAsync())
                {
                    while (await reader.ReadAsync())
                    {
                        candidates.Add((
                            reader.GetInt32(0),
                            reader.IsDBNull(1) ? "" : reader.GetString(1),
                            reader.IsDBNull(2) ? "" : reader.GetString(2)
                        ));
                    }
                }
            }

            Console.WriteLine("Successful leads pending Source assignment: " + candidates.Count);

            int updated = 0, unresolved = 0, errors = 0;

            // Separate connections since Thamesbank is a different server instance -
            // cross-database three-part names only work on the same instance, so each
            // update goes to its own connection instead.
            using (var leadsConn = new SqlConnection(DB_CONNECTION_STRING))
            using (var thamesConn = new SqlConnection(THAMESBANK_CONNECTION_STRING))
            {
                await leadsConn.OpenAsync();
                await thamesConn.OpenAsync();

                foreach (var row in candidates)
                {
                    string source = DetermineSourceFromSubject(row.EmailSubject);

                    if (source == null)
                    {
                        Console.WriteLine($"  LeadId {row.LeadId}: no known source matched subject \"{row.EmailSubject}\" - left as Success");
                        unresolved++;
                        continue;
                    }

                    try
                    {
                        const string updateProspectSql = @"
                            UPDATE dbo.icp_Daprospect
                            SET Source_CR01_VTId = (
                                SELECT VTId FROM dbo.icp_CR01_VT WHERE VTDescription = @Source
                            )
                            WHERE Refno = @EpaProspectRef";

                        using (var cmd = new SqlCommand(updateProspectSql, thamesConn))
                        {
                            cmd.Parameters.AddWithValue("@Source", source);
                            cmd.Parameters.AddWithValue("@EpaProspectRef", row.EpaProspectRef);
                            await cmd.ExecuteNonQueryAsync();
                        }

                        const string updateStatusSql = @"
                            UPDATE dbo.PartnerLeads
                            SET Status = 'Success-SourceSet'
                            WHERE LeadId = @LeadId";

                        using (var cmd = new SqlCommand(updateStatusSql, leadsConn))
                        {
                            cmd.Parameters.AddWithValue("@LeadId", row.LeadId);
                            await cmd.ExecuteNonQueryAsync();
                        }

                        Console.WriteLine($"  LeadId {row.LeadId}: Source set to '{source}' for Refno {row.EpaProspectRef}");
                        updated++;
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"  LeadId {row.LeadId}: error setting source - {ex.Message}");
                        errors++;
                    }
                }
            }

            Console.WriteLine($"Source assignment complete. Updated: {updated}, Unresolved (no keyword match): {unresolved}, Errors: {errors}");
        }

