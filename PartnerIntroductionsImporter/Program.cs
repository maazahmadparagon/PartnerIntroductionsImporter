        static async Task Main(string[] args)
        {
            // Mirror all console output into a daily log file (Logs\ next to the exe) so
            // every run can be reviewed afterwards.
            var originalOut = Console.Out;
            StreamWriter logFile = null;
            try
            {
                string logDir = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "Logs");
                System.IO.Directory.CreateDirectory(logDir);
                string logPath = Path.Combine(logDir, "PartnerIntroductionsImporter_" + DateTime.Now.ToString("yyyyMMdd") + ".log");
                logFile = new StreamWriter(logPath, append: true, encoding: Encoding.UTF8) { AutoFlush = true };
                Console.SetOut(new TeeWriter(originalOut, logFile));
            }
            catch (Exception logEx)
            {
                Console.WriteLine("WARNING: could not open log file - console output only: " + logEx.Message);
            }

            try
            {
                await Run(args);
            }
            finally
            {
                Console.SetOut(originalOut);
                logFile?.Dispose();
            }
        }

