        // Decodes the double-escaped SOAP/XML response and extracts success + refs + error text.
        static (bool Success, string Prospect, string Policy, string ErrorSummary) ParseInStreamResponse(string rawResponseXml)
        {
            string decoded = System.Net.WebUtility.HtmlDecode(System.Net.WebUtility.HtmlDecode(rawResponseXml ?? ""));

            bool success = Regex.IsMatch(decoded, "<Success>true</Success>", RegexOptions.IgnoreCase);
            string prospect = Regex.Match(decoded, "<EPAPROSPECT>(.*?)</EPAPROSPECT>").Groups[1].Value;
            string policy = Regex.Match(decoded, "<EPAPOLICY>(.*?)</EPAPOLICY>").Groups[1].Value;

            string errorSummary = "";
            if (!success)
            {
                var errorLines = Regex.Matches(decoded, "<EPALINE>(.*?)</EPALINE>", RegexOptions.Singleline)
                    .Cast<Match>().Select(m => m.Groups[1].Value.Trim()).ToList();

                errorSummary = errorLines.Count > 0
                    ? string.Join(" | ", errorLines)
                    : "Import failed - see RawResponse column for full detail";
            }

            return (success, prospect, policy, errorSummary);
        }

