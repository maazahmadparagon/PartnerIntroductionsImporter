        static string GetFieldValue(string emailBody, string fieldName)
        {
            try
            {
                string searchText = fieldName + " -";
                int startIndex = emailBody.IndexOf(searchText, StringComparison.OrdinalIgnoreCase);
                if (startIndex == -1)
                {
                    searchText = fieldName + "-";
                    startIndex = emailBody.IndexOf(searchText, StringComparison.OrdinalIgnoreCase);
                }
                if (startIndex == -1) return null;

                startIndex += searchText.Length;
                int endIndex = emailBody.IndexOf("\n", startIndex);
                if (endIndex == -1) endIndex = emailBody.Length;

                string value = emailBody.Substring(startIndex, endIndex - startIndex).Trim();
                value = Regex.Replace(value, "<.*?>", "").Trim();

                return string.IsNullOrWhiteSpace(value) ? null : value;
            }
            catch
            {
                return null;
            }
        }

        // "Post Code" is sometimes run straight into the value with no separator at all
        // (e.g. "Post CodeBT12 4LW"), which GetFieldValue's " -" / "-" search misses entirely.
        // This handles both that format and the normal "Post Code - X" format.
        static string GetPostCode(string emailBody)
        {
            // Try the normal dash-separated format first.
            string normal = GetFieldValue(emailBody, "Post Code");
            if (!string.IsNullOrWhiteSpace(normal)) return normal;

            // Fall back to matching a UK postcode pattern directly after "Post Code" with no separator.
            var match = Regex.Match(emailBody,
                @"Post\s*Code\s*([A-Z]{1,2}\d[A-Z\d]?\s*\d[A-Z]{2})",
                RegexOptions.IgnoreCase);

            if (match.Success)
                return match.Groups[1].Value.Trim().ToUpperInvariant();

            return null;
        }

        static (string Title, string Forenames, string Surname) SplitName(string fullName)
        {
            if (string.IsNullOrWhiteSpace(fullName))
                return ("", "", "Unknown");

            var parts = fullName.Replace(".", "").Trim().Split(new char[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
            if (parts.Length == 0) return ("", "", "Unknown");

            string title = "";
            int startIdx = 0;

            foreach (var known in KnownTitles)
            {
                if (parts[0].Equals(known, StringComparison.OrdinalIgnoreCase))
                {
                    title = known;
                    startIdx = 1;
                    break;
                }
            }

            if (parts.Length - startIdx <= 0) return (title, "", "Unknown");
            if (parts.Length - startIdx == 1) return (title, "", parts[startIdx]);

            string surname = parts[parts.Length - 1];
            string forenames = string.Join(" ", parts, startIdx, parts.Length - startIdx - 1);

            return (title, forenames, surname);
        }

        static int ExtractNumber(string value, int fallback = 0)
        {
            if (string.IsNullOrWhiteSpace(value)) return fallback;

            var match = Regex.Match(value, @"(\d+(\.\d+)?)\s*([kK])?");
            if (!match.Success) return fallback;

            double number = double.Parse(match.Groups[1].Value);
            if (match.Groups[3].Success) number *= 1000;

            return (int)number;
        }

        static bool CoverIncludes(string coverType, string keyword)
        {
            return !string.IsNullOrWhiteSpace(coverType) &&
                   coverType.IndexOf(keyword, StringComparison.OrdinalIgnoreCase) >= 0;
        }

        // "Semi-Detached House" is the ONE Housetype value confirmed working via live testing
        // (James Mackey's successful import). Both the abbreviated list and the full readable
        // list we were given have since failed live testing for other values ("Detached Bungalow"
        // was rejected even as an exact match), so until the correct accepted vocabulary is
        // confirmed with Open GI, everything not exactly this proven value falls back to it.
        private const string DEFAULT_HOUSETYPE = "Semi-Detached House";

        static string NormalizeHousetype(string raw)
        {
            if (string.IsNullOrWhiteSpace(raw)) return DEFAULT_HOUSETYPE;

            string trimmed = raw.Trim();
            if (trimmed.Equals(DEFAULT_HOUSETYPE, StringComparison.OrdinalIgnoreCase))
                return DEFAULT_HOUSETYPE;

            // Everything else is unverified against the back office right now - safer to fall
            // back to the proven value than risk another rejected import on a guess.
            return DEFAULT_HOUSETYPE;
        }

        static string SanitizeOccupation(string occupation)
        {
            if (string.IsNullOrWhiteSpace(occupation)) return DEFAULT_OCCUPATION;
            return ValidOccupations.Contains(occupation.Trim()) ? occupation.Trim() : DEFAULT_OCCUPATION;
        }

