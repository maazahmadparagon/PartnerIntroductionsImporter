        // Determines the prospect Source value by matching known keywords against the
        // email subject line. Returns null if none of the known sources match.
        static string DetermineSourceFromSubject(string subject)
        {
            if (string.IsNullOrWhiteSpace(subject)) return null;

            foreach (var source in KnownSources)
            {
                if (subject.IndexOf(source, StringComparison.OrdinalIgnoreCase) >= 0)
                    return source;
            }

            return null;
        }

